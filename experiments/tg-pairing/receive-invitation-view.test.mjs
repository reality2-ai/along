import assert from 'node:assert/strict';
import AxeBuilder from '@axe-core/playwright';
import {createServer} from 'node:http';
import {readFile} from 'node:fs/promises';
import {join} from 'node:path';
const {chromium} = await import(process.env.PLAYWRIGHT_MODULE || '@playwright/test');
const sources = new Map();
for (const name of ['storage.mjs', 'membership.mjs', 'certificate.mjs', 'invitation.mjs']) sources.set('/' + name, await readFile(join(process.env.R2_BROWSER_DIR, name)));
for (const name of ['software-persona.mjs', 'local-persona.mjs', 'software-invitation.mjs', 'receive-invitation-view.mjs', 'comparison.css']) sources.set('/' + name, await readFile(new URL(name, import.meta.url)));
for (const name of ['hive_wasm.js', 'hive_wasm_bg.wasm']) sources.set('/' + name, await readFile(join(process.env.R2_WASM_DIR, name)));
for (const name of ['qr-transfer.mjs', 'vendor/qrcode.mjs']) sources.set('/' + name, await readFile(new URL(name, import.meta.url)));
const server = createServer((req, res) => {
  res.setHeader('Content-Type', req.url.endsWith('.css') ? 'text/css' : req.url.endsWith('.wasm') ? 'application/wasm' : sources.has(req.url) ? 'text/javascript' : 'text/html');
  res.end(sources.get(req.url) || '<!doctype html><html lang="en"><head><meta name="viewport" content="width=device-width,initial-scale=1"><title>Local setup</title><link rel="stylesheet" href="/comparison.css"></head><body><main><h1>Connect your devices</h1><div id="setup"></div></main></body></html>');
});
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
let browser;
try {
  browser = await chromium.launch({headless: true, executablePath: process.env.CHROMIUM_PATH});
  const context = await browser.newContext({viewport: {width: 320, height: 640}, reducedMotion: 'reduce'});
  const page = await context.newPage(); await page.goto(`http://127.0.0.1:${server.address().port}`);
  await page.evaluate(async () => {
    window.module = await import('./receive-invitation-view.mjs'); window.backCount = 0;
    window.mount = () => module.showReceiveInvitation(document.querySelector('#setup'), {focus: true, onBack: () => { backCount++; }});
    window.view = mount(); window.resolved = false;
    view.completed.then(() => { window.resolved = true; }, () => {});
  });
  assert.equal(await page.evaluate(() => document.activeElement.tagName), 'H2');
  await page.getByRole('button', {name: 'Review invitation', exact: true}).click();
  await page.getByRole('status').filter({hasText: 'could not be read'}).waitFor();
  assert.equal(await page.getByLabel('Invitation text').getAttribute('aria-invalid'), 'true');
  const descriptor = JSON.stringify({profile: 'along-browser-invitation-v2', group: '11'.repeat(32), issuer: '22'.repeat(32), code: '33'.repeat(16), validity: '8', epoch: '0'});
  await page.getByLabel('Invitation text').fill(descriptor);
  assert.equal(await page.getByLabel('Invitation text').getAttribute('aria-invalid'), null);
  await page.evaluate(() => document.querySelector('.pairing-primary').click());
  assert.equal(await page.getByRole('heading', {name: 'Paste your invitation'}).count(), 1);
  await page.getByRole('button', {name: 'Review invitation', exact: true}).focus();
  await page.keyboard.press('Enter');
  assert.equal(await page.evaluate(() => document.activeElement.textContent), 'Is this from your other device?');
  assert.equal(await page.evaluate(() => resolved), false);
  await page.evaluate(() => document.documentElement.style.fontSize = '200%');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.deepEqual((await new AxeBuilder({page}).analyze()).violations.map(v => v.id), []);
  await page.keyboard.press('Escape');
  assert.equal(await page.evaluate(() => document.activeElement.tagName), 'TEXTAREA');
  assert.equal(await page.evaluate(() => backCount), 0);
  assert.equal(await page.getByLabel('Invitation text').inputValue(), descriptor);
  await page.getByRole('button', {name: 'Review invitation', exact: true}).click();
  await page.evaluate(() => document.querySelector('.pairing-primary').click());
  assert.equal(await page.evaluate(() => resolved), false);
  await page.getByRole('button', {name: 'Use invitation from my other device', exact: true}).focus();
  await page.keyboard.press('Enter');
  assert.equal(await page.evaluate(async () => (await view.completed).descriptor), descriptor);
  assert.equal(await page.evaluate(() => document.activeElement.textContent), 'Back');
  assert.equal(await page.getByLabel('Invitation text').inputValue(), '');
  assert.deepEqual((await new AxeBuilder({page}).analyze()).violations.map(v => v.id), []);
  await page.keyboard.press('Escape');
  assert.equal(await page.evaluate(async () => backCount === 1 && (await view.completed).signal.aborted), true);
  await page.evaluate(() => { window.view = mount(); window.old = view; window.view = mount(); });
  assert.equal(await page.evaluate(() => old.completed.then(() => false, () => true)), true);
  await page.getByLabel('Invitation text').fill('<img src=x onerror=alert(1)>');
  await page.getByRole('button', {name: 'Review invitation', exact: true}).click();
  assert.equal(await page.locator('img').count(), 0);
  assert.equal(await page.getByRole('heading', {name: 'Paste your invitation'}).count(), 1);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  console.log('PASS: invitation review requires two trusted actions; invalid input, Back/edit, cancellation/replacement, keyboard focus, axe and 320px/200% reflow. Format review is not source authentication.');
} finally { await browser?.close(); await new Promise(resolve => server.close(resolve)); }
